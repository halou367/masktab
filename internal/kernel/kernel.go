// Package kernel 是内核无关层（计划 D2 / KernelAdapter）：所有与浏览器内核有关的细节
// （启动参数、目录路径、能力差异、下载地址）只允许出现在这个包里。
package kernel

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

// Launch 是一次实例启动所需的、与内核无关的配置。
type Launch struct {
	ProfileDir          string
	No                  int
	Normal              bool // 普通窗口 #0：不带指纹与时区参数
	ProxyPort           int  // 0 = 不带代理参数（仅当 mihomo 不可用且为 #0 时）
	Extensions          []string
	Color               [3]int
	Seed                uint32
	HardwareConcurrency int
	PlatformVersion     string
	Platform            string // 空 = 与本机一致
	Brand               string // 空 = Chrome
	DisableSpoofing     []string
	Timezone            string
	Lang                string
	AcceptLang          string
	StartURL            string
	NewTabURL           string // 新标签页地址（伴随扩展的页面）；内核支持 --custom-ntp 时使用
}

type Caps struct {
	Fingerprint bool `json:"fingerprint"` // 引擎级指纹
	Timezone    bool `json:"timezone"`    // 可靠的时区开关
	// 以下几项决定界面上显示哪些设置（同一份界面，电脑和手机按能力显示）。
	Platform bool `json:"platform"` // 可以选伪装成哪种系统、哪个浏览器、几核
	Spoof    bool `json:"spoof"`    // 伪装项可以逐项开关
	ExtLib   bool `json:"extLib"`   // 有全局扩展库（Chrome 应用商店 / 本机文件）
	Live     bool `json:"live"`     // 改时区、语言、指纹不用重启实例
}

type Adapter interface {
	Name() string
	Caps() Caps
	Args(l Launch) []string
	Env(l Launch) []string
	// ExtDataDirs 返回某扩展在一个用户数据目录里的全部数据位置（计划 8.11）。
	ExtDataDirs(profileDir, extID string) []string
	PrefsPath(profileDir string) string
}

func Get(name string) Adapter {
	if name == "ungoogled" {
		return ungoogled{}
	}
	return fpChromium{}
}

func hostPlatform() string {
	switch runtime.GOOS {
	case "windows":
		return "windows"
	case "darwin":
		return "macos"
	}
	return "linux"
}

func orDefault(v, d string) string {
	if v == "" {
		return d
	}
	return v
}

// HostPlatform 返回本机系统在指纹参数里的名字（windows | macos | linux）。
func HostPlatform() string { return hostPlatform() }

// commonArgs 是两种内核共用的参数。硬规则 R-1 在这里落实。
func commonArgs(l Launch) []string {
	a := []string{
		"--user-data-dir=" + l.ProfileDir,
		"--no-first-run", "--no-default-browser-check", "--disable-background-mode",
		"--restore-last-session", "--hide-crash-restore-bubble",
		"--force-webrtc-ip-handling-policy=disable_non_proxied_udp",
		fmt.Sprintf("--install-autogenerated-theme=%d,%d,%d", l.Color[0], l.Color[1], l.Color[2]),
		fmt.Sprintf("--window-name=#%d", l.No),
		// 没开“开发者模式”时，内核会把从文件夹加载的扩展停用（伴随扩展、本地扩展都是这样加载的）。刚启动时它不查，
		// 可扩展一重新加载就查——在 chrome://extensions 里点一下“在无痕模式下启用”就会重新加载，于是伴随扩展被停用，
		// 还要用户自己去开开发者模式、再把扩展打开；关掉内核重开也好不了（需求方 2026-11-17 遇到，decisions U-2 补充）。
		// 开发者模式是“受保护偏好”，从外面写不进去（decisions U-2），所以用内核自己的开关把这项检查关掉。
		// 已经被这样停用的，带上这个参数重开就自己好了。每次冒烟都实测（scripts/ext-reload-e2e.mjs）。
		// 注意：内核只认最后一个 --disable-features，以后要再关别的功能得写在同一个参数里（用逗号隔开）。
		"--disable-features=ExtensionDisableUnsupportedDeveloper",
	}
	if l.ProxyPort > 0 {
		a = append(a,
			fmt.Sprintf("--proxy-server=socks5://127.0.0.1:%d", l.ProxyPort),
			"--host-resolver-rules=MAP * ~NOTFOUND , EXCLUDE 127.0.0.1",
			// 上面这个参数在内核的"危险参数"名单里，每次启动都会在第一个标签页顶上出一条
			// "您使用的是不受支持的命令行标记…稳定性和安全性会有所下降"。它是我们故意加的（防 DNS 泄漏，R-1），
			// 这条提示没有意义。内核里只有两个办法不出这条提示：企业策略（要写注册表，还会显示"由贵单位管理"），
			// 或者 --test-type。后者的其他影响见 docs/decisions.md U-3，网页侧看不出区别。
			"--test-type",
		)
	}
	if len(l.Extensions) > 0 {
		a = append(a, "--load-extension="+strings.Join(l.Extensions, ","))
	}
	if l.Lang != "" {
		a = append(a, "--lang="+l.Lang)
	}
	if l.AcceptLang != "" {
		a = append(a, "--accept-lang="+l.AcceptLang)
	}
	return a
}

func extDataDirs(profileDir, extID string) []string {
	d := filepath.Join(profileDir, "Default")
	return []string{
		filepath.Join(d, "Local Extension Settings", extID),
		filepath.Join(d, "Sync Extension Settings", extID),
		filepath.Join(d, "Managed Extension Settings", extID),
		filepath.Join(d, "IndexedDB", "chrome-extension_"+extID+"_0.indexeddb.leveldb"),
		filepath.Join(d, "IndexedDB", "chrome-extension_"+extID+"_0.indexeddb.blob"),
		filepath.Join(d, "DNR Extension Rules", extID),
		filepath.Join(d, "Extension Scripts", extID),
	}
}

// ---- fingerprint-chromium（默认）----

type fpChromium struct{}

func (fpChromium) Name() string { return "fingerprint-chromium" }
func (fpChromium) Caps() Caps {
	return Caps{Fingerprint: true, Timezone: true, Platform: true, Spoof: true, ExtLib: true}
}
func (fpChromium) Env(Launch) []string               { return nil }
func (fpChromium) PrefsPath(p string) string         { return filepath.Join(p, "Default", "Preferences") }
func (fpChromium) ExtDataDirs(p, id string) []string { return extDataDirs(p, id) }
func (fpChromium) Args(l Launch) []string {
	a := commonArgs(l)
	a = append(a, customNTP(l)...)
	if !l.Normal {
		a = append(a,
			fmt.Sprintf("--fingerprint=%d", l.Seed),
			"--fingerprint-platform="+orDefault(l.Platform, hostPlatform()),
			"--fingerprint-brand="+orDefault(l.Brand, "Chrome"),
		)
		if l.HardwareConcurrency > 0 {
			a = append(a, fmt.Sprintf("--fingerprint-hardware-concurrency=%d", l.HardwareConcurrency))
		}
		if l.PlatformVersion != "" {
			a = append(a, "--fingerprint-platform-version="+l.PlatformVersion)
		}
		if len(l.DisableSpoofing) > 0 {
			a = append(a, "--disable-spoofing="+strings.Join(l.DisableSpoofing, ","))
		}
		if l.Timezone != "" {
			a = append(a, "--timezone="+l.Timezone)
		}
	}
	if l.StartURL != "" {
		a = append(a, l.StartURL)
	}
	return a
}

// ---- Ungoogled Chromium（备选：没有引擎级指纹；时区在 Windows 上不可靠）----

type ungoogled struct{}

func (ungoogled) Name() string { return "ungoogled" }
func (ungoogled) Caps() Caps {
	return Caps{Fingerprint: false, Timezone: runtime.GOOS != "windows", Platform: true, Spoof: true, ExtLib: true}
}
func (ungoogled) PrefsPath(p string) string         { return filepath.Join(p, "Default", "Preferences") }
func (ungoogled) ExtDataDirs(p, id string) []string { return extDataDirs(p, id) }
func (ungoogled) Env(l Launch) []string {
	if !l.Normal && l.Timezone != "" {
		return []string{"TZ=" + l.Timezone}
	}
	return nil
}
func (ungoogled) Args(l Launch) []string {
	a := commonArgs(l)
	a = append(a, customNTP(l)...)
	if l.StartURL != "" {
		a = append(a, l.StartURL)
	}
	return a
}

// ExeName 返回内核可执行文件名。
func ExeName() string {
	if runtime.GOOS == "windows" {
		return "chrome.exe"
	}
	return "chrome"
}

// Find 在 <数据目录>/kernel 下找内核可执行文件（最多向下 4 层），多个版本时取路径排序最大的。
func Find(kernelDir, override string) string {
	if override != "" {
		if st, err := os.Stat(override); err == nil && !st.IsDir() {
			return override
		}
	}
	var found []string
	root := filepath.Clean(kernelDir)
	_ = filepath.WalkDir(root, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() {
			if strings.Count(strings.TrimPrefix(p, root), string(filepath.Separator)) > 4 {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Name() == ExeName() {
			// 自动下载目录里只认当前固定的版本：换了固定版本后，旧版本目录不再被选中，会触发重新下载。
			auto := filepath.Join(root, "fingerprint-chromium") + string(filepath.Separator)
			if strings.HasPrefix(p, auto) && !strings.HasPrefix(p, auto+KernelVersion+string(filepath.Separator)) {
				return nil
			}
			found = append(found, p)
		}
		return nil
	})
	if len(found) == 0 {
		return ""
	}
	sort.Strings(found)
	return found[len(found)-1]
}

// customNTP 用 ungoogled-chromium 系内核自带的 --custom-ntp 把新标签页指到伴随扩展的页面。
// 不用扩展清单里的 chrome_url_overrides：那样内核会弹“Did you mean to change this page?”，
// 用户点了默认的“Change it back”伴随扩展就被停用了；这个确认状态存在受保护的偏好里，没法预先写入（docs/decisions.md U-1）。
func customNTP(l Launch) []string {
	if l.NewTabURL == "" {
		return nil
	}
	return []string{"--custom-ntp=" + l.NewTabURL}
}
