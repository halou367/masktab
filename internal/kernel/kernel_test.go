package kernel

import (
	"strings"
	"testing"
)

func has(args []string, want string) bool {
	for _, a := range args {
		if a == want {
			return true
		}
	}
	return false
}

func TestArgs(t *testing.T) {
	l := Launch{ProfileDir: "/p/3", No: 3, ProxyPort: 17893, Extensions: []string{"/e/a", "/e/b"}, Color: [3]int{26, 115, 232},
		Seed: 12345, HardwareConcurrency: 8, Timezone: "Asia/Tokyo", Lang: "ja-JP", AcceptLang: "ja-JP,ja,en"}
	a := Get("fingerprint-chromium").Args(l)
	for _, w := range []string{"--user-data-dir=/p/3", "--proxy-server=socks5://127.0.0.1:17893", "--host-resolver-rules=MAP * ~NOTFOUND , EXCLUDE 127.0.0.1", "--test-type",
		"--load-extension=/e/a,/e/b", "--fingerprint=12345", "--fingerprint-hardware-concurrency=8", "--timezone=Asia/Tokyo", "--lang=ja-JP",
		"--install-autogenerated-theme=26,115,232", "--restore-last-session"} {
		if !has(a, w) {
			t.Errorf("缺少参数 %s", w)
		}
	}
	// 不带这个参数的话，用户在扩展页点一下“在无痕模式下启用”，伴随扩展就被内核停用（见 commonArgs 里的说明）。
	// 内核只认最后一个 --disable-features，所以两个适配器都只能有一个。
	for _, k := range []string{"fingerprint-chromium", "ungoogled"} {
		n, ok := 0, false
		for _, x := range Get(k).Args(l) {
			if strings.HasPrefix(x, "--disable-features=") {
				n++
				ok = ok || strings.Contains(","+strings.TrimPrefix(x, "--disable-features=")+",", ",ExtensionDisableUnsupportedDeveloper,")
			}
		}
		if n != 1 || !ok {
			t.Errorf("%s：--disable-features 应该正好有一个、里面有 ExtensionDisableUnsupportedDeveloper（有 %d 个，含=%v）", k, n, ok)
		}
	}
	// 节能模式（decisions PERF-2）：后台服务并进同一个 --disable-features；性能模式不带
	l.Saver = true
	if !has(Get("fingerprint-chromium").Args(l), disableFeatures(true)) || !strings.Contains(disableFeatures(true), ",OptimizationHints,") {
		t.Errorf("节能模式应关掉后台服务：%s", disableFeatures(true))
	}
	l.Saver = false
	if !has(Get("fingerprint-chromium").Args(l), "--disable-features=ExtensionDisableUnsupportedDeveloper") {
		t.Errorf("性能模式只应关 ExtensionDisableUnsupportedDeveloper")
	}
	l.Normal = true
	for _, x := range Get("fingerprint-chromium").Args(l) {
		if strings.HasPrefix(x, "--fingerprint") || strings.HasPrefix(x, "--timezone") {
			t.Errorf("普通窗口不应带 %s", x)
		}
	}
	l.Normal, l.ProxyPort = false, 0
	for _, x := range Get("ungoogled").Args(l) {
		// --test-type 只为了不出"不受支持的命令行标记"提示条，没有 --host-resolver-rules 时不该带
		if strings.HasPrefix(x, "--fingerprint=") || strings.HasPrefix(x, "--proxy-server") || strings.HasPrefix(x, "--host-resolver-rules") || x == "--test-type" {
			t.Errorf("不应带 %s", x)
		}
	}
}

// 合并窗口：新窗口带着位置和大小启动（decisions UI-31）；没给、或者小得不像话就不带，浏览器用自己记的。
func TestArgsBounds(t *testing.T) {
	l := Launch{ProfileDir: "/p/3", No: 3, Bounds: &[4]int{-1530, 40, 1280, 800}}
	a := Get("fingerprint-chromium").Args(l)
	if !has(a, "--window-position=-1530,40") || !has(a, "--window-size=1280,800") {
		t.Fatalf("应带窗口位置和大小：%v", a)
	}
	for _, b := range []*[4]int{nil, {0, 0, 120, 80}} {
		l.Bounds = b
		for _, x := range Get("ungoogled").Args(l) {
			if strings.HasPrefix(x, "--window-position") || strings.HasPrefix(x, "--window-size") {
				t.Fatalf("不该带窗口位置：%v", x)
			}
		}
	}
}
