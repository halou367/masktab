package kernel

import (
	"strings"
	"testing"
)

func has(args []string, want string) bool {
	for _, a := range args {
		if a == want {
			return true
		}
	}
	return false
}

func TestArgs(t *testing.T) {
	l := Launch{ProfileDir: "/p/3", No: 3, ProxyPort: 17893, Extensions: []string{"/e/a", "/e/b"}, Color: [3]int{26, 115, 232},
		Seed: 12345, HardwareConcurrency: 8, Timezone: "Asia/Tokyo", Lang: "ja-JP", AcceptLang: "ja-JP,ja,en"}
	a := Get("fingerprint-chromium").Args(l)
	for _, w := range []string{"--user-data-dir=/p/3", "--proxy-server=socks5://127.0.0.1:17893", "--host-resolver-rules=MAP * ~NOTFOUND , EXCLUDE 127.0.0.1",
		"--load-extension=/e/a,/e/b", "--fingerprint=12345", "--fingerprint-hardware-concurrency=8", "--timezone=Asia/Tokyo", "--lang=ja-JP",
		"--install-autogenerated-theme=26,115,232", "--restore-last-session"} {
		if !has(a, w) {
			t.Errorf("缺少参数 %s", w)
		}
	}
	l.Normal = true
	for _, x := range Get("fingerprint-chromium").Args(l) {
		if strings.HasPrefix(x, "--fingerprint") || strings.HasPrefix(x, "--timezone") {
			t.Errorf("普通窗口不应带 %s", x)
		}
	}
	l.Normal, l.ProxyPort = false, 0
	for _, x := range Get("ungoogled").Args(l) {
		if strings.HasPrefix(x, "--fingerprint=") || strings.HasPrefix(x, "--proxy-server") {
			t.Errorf("不应带 %s", x)
		}
	}
}
